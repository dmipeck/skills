"""Pure triage decision helpers (no forge or typesafe-sdk I/O)."""

from __future__ import annotations

from dataclasses import dataclass

CATEGORIES = frozenset({"bug", "enhancement"})
STATES = frozenset({"needs-info", "ready-for-agent", "ready-for-human", "wontfix"})
DISCLAIMER = "> *This was generated by AI during triage.*"


@dataclass(frozen=True)
class ChoiceResult:
    choice: str
    confidence: float


@dataclass(frozen=True)
class Classification:
    category: ChoiceResult
    state: ChoiceResult


@dataclass(frozen=True)
class GateDecision:
    apply: bool
    reason: str


def validate_confidence(value: float) -> float:
    if not 0.0 <= value <= 1.0:
        raise ValueError(f"min-confidence must be in [0, 1], got {value}")
    return value


def validate_classification(classification: Classification) -> Classification:
    if classification.category.choice not in CATEGORIES:
        raise ValueError(f"unknown category {classification.category.choice!r}")
    if classification.state.choice not in STATES:
        raise ValueError(f"unknown state {classification.state.choice!r}")
    for part in (classification.category, classification.state):
        if not 0.0 <= part.confidence <= 1.0:
            raise ValueError(f"confidence must be in [0, 1], got {part.confidence}")
    return classification


def gate(classification: Classification, min_confidence: float) -> GateDecision:
    """Apply writes only when both Choice confidences meet the threshold."""
    validate_classification(classification)
    threshold = validate_confidence(min_confidence)
    if classification.category.confidence < threshold:
        return GateDecision(
            False,
            (
                f"category confidence {classification.category.confidence:.4f} "
                f"< min-confidence {threshold:.4f}"
            ),
        )
    if classification.state.confidence < threshold:
        return GateDecision(
            False,
            (
                f"state confidence {classification.state.confidence:.4f} "
                f"< min-confidence {threshold:.4f}"
            ),
        )
    return GateDecision(True, "")


def labels_after_apply(
    current: frozenset[str] | set[str],
    classification: Classification,
    *,
    triage_label: str,
) -> tuple[frozenset[str], frozenset[str]]:
    """Return (to_add, to_remove) for category+state apply and triage drop."""
    validate_classification(classification)
    current_set = frozenset(current)
    wanted = {classification.category.choice, classification.state.choice}
    remove = ((CATEGORIES | STATES | {triage_label}) - wanted) & current_set
    add = wanted - current_set
    return frozenset(add), frozenset(remove)


def format_comment(classification: Classification) -> str:
    validate_classification(classification)
    return (
        f"{DISCLAIMER}\n\n"
        f"**category:** `{classification.category.choice}` "
        f"(confidence {classification.category.confidence:.4f})\n"
        f"**state:** `{classification.state.choice}` "
        f"(confidence {classification.state.confidence:.4f})\n"
    )


def build_state(*, title: str, body: str, comments: tuple[str, ...] = ()) -> dict[str, object]:
    payload: dict[str, object] = {
        "title": title,
        "body": body or "",
    }
    if comments:
        payload["recent_comments"] = list(comments)
    return payload
